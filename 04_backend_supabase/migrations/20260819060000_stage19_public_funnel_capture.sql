  p_landing_path text,
  p_source text default null,
  p_medium text default null,
  p_campaign text default null,
  p_term text default null,
  p_content text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if lower(btrim(coalesce(p_event_name, ''))) not in ('landing_view', 'signup_started') then
    raise exception using errcode = '22023', message = 'PUBLIC_GROWTH_EVENT_NOT_ALLOWED';
  end if;

  if char_length(btrim(coalesce(p_visitor_key, ''))) < 24
    or char_length(btrim(coalesce(p_visitor_key, ''))) > 128
  then
    raise exception using errcode = '22023', message = 'INVALID_PUBLIC_VISITOR_KEY';
  end if;

  if char_length(btrim(coalesce(p_landing_path, ''))) < 1
    or char_length(btrim(coalesce(p_landing_path, ''))) > 500
    or left(btrim(coalesce(p_landing_path, '')), 1) <> '/'
    or position('?' in btrim(coalesce(p_landing_path, ''))) > 0
    or position('#' in btrim(coalesce(p_landing_path, ''))) > 0
  then
    raise exception using errcode = '22023', message = 'INVALID_PUBLIC_LANDING_PATH';
  end if;

  return telemetry_private.capture_public_growth_event_authority(
    p_event_name,
    p_visitor_key,
    p_landing_path,
    p_source,
    p_medium,
    p_campaign,
    p_term,
    p_content
