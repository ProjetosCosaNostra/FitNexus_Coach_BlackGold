create schema if not exists telemetry_private;

revoke all on schema telemetry_private from public;
grant usage on schema telemetry_private to anon, authenticated, service_role;

create table if not exists telemetry_private.public_growth_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('landing_view', 'signup_started')),
  visitor_key_hash text not null check (visitor_key_hash ~ '^[0-9a-f]{64}$'),
  touch_hash text not null check (touch_hash ~ '^[0-9a-f]{64}$'),
  landing_path text not null check (
    char_length(landing_path) between 1 and 500
    and left(landing_path, 1) = '/'
    and position('?' in landing_path) = 0
    and position('#' in landing_path) = 0
  ),
  source text,
  medium text,
  campaign text,
  term text,
  content text,
  event_day date not null default current_date,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  check (source is null or char_length(source) between 1 and 100),
  check (medium is null or char_length(medium) between 1 and 100),
  check (campaign is null or char_length(campaign) between 1 and 160),
  check (term is null or char_length(term) between 1 and 160),
  check (content is null or char_length(content) between 1 and 160)
);

create unique index if not exists public_growth_events_dedupe_uidx
  on telemetry_private.public_growth_events(
    event_name,
    visitor_key_hash,
    landing_path,
    touch_hash,
    event_day
  );

create index if not exists public_growth_events_name_occurred_idx
  on telemetry_private.public_growth_events(event_name, occurred_at desc);

create index if not exists public_growth_events_campaign_occurred_idx
  on telemetry_private.public_growth_events(source, medium, campaign, occurred_at desc)
  where source is not null or medium is not null or campaign is not null;

revoke all on telemetry_private.public_growth_events from public, anon, authenticated;
revoke all on telemetry_private.public_growth_events from service_role;
grant select on telemetry_private.public_growth_events to service_role;

create or replace function telemetry_private.capture_public_growth_event_authority(
  p_event_name text,
  p_visitor_key text,
  p_landing_path text,
  p_source text default null,
  p_medium text default null,
  p_campaign text default null,
  p_term text default null,
  p_content text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event_name text := lower(btrim(coalesce(p_event_name, '')));
  v_visitor_key text := btrim(coalesce(p_visitor_key, ''));
  v_landing_path text := btrim(coalesce(p_landing_path, ''));
  v_source text := nullif(left(btrim(coalesce(p_source, '')), 100), '');
  v_medium text := nullif(left(btrim(coalesce(p_medium, '')), 100), '');
  v_campaign text := nullif(left(btrim(coalesce(p_campaign, '')), 160), '');
  v_term text := nullif(left(btrim(coalesce(p_term, '')), 160), '');
  v_content text := nullif(left(btrim(coalesce(p_content, '')), 160), '');
  v_visitor_hash text;
  v_touch_hash text;
  v_inserted_id bigint;
begin
  if v_event_name not in ('landing_view', 'signup_started') then
    raise exception using errcode = '22023', message = 'PUBLIC_GROWTH_EVENT_NOT_ALLOWED';
  end if;

  if char_length(v_visitor_key) < 24
    or char_length(v_visitor_key) > 128
    or v_visitor_key !~ '^[A-Za-z0-9_-]+$'
  then
    raise exception using errcode = '22023', message = 'INVALID_PUBLIC_VISITOR_KEY';
  end if;

  if char_length(v_landing_path) < 1
    or char_length(v_landing_path) > 500
    or left(v_landing_path, 1) <> '/'
    or position('?' in v_landing_path) > 0
    or position('#' in v_landing_path) > 0
  then
    raise exception using errcode = '22023', message = 'INVALID_PUBLIC_LANDING_PATH';
  end if;

  v_visitor_hash := encode(
    extensions.digest(v_visitor_key, 'sha256'),
    'hex'
  );
  v_touch_hash := encode(
    extensions.digest(
      concat_ws('|',
        coalesce(v_source, ''),
        coalesce(v_medium, ''),
        coalesce(v_campaign, ''),
        coalesce(v_term, ''),
        coalesce(v_content, '')
      ),
      'sha256'
    ),
    'hex'
  );

  insert into telemetry_private.public_growth_events (
    event_name,
    visitor_key_hash,
    touch_hash,
    landing_path,
    source,
    medium,
    campaign,
    term,
    content
  )
  values (
    v_event_name,
    v_visitor_hash,
    v_touch_hash,
    v_landing_path,
    v_source,
    v_medium,
    v_campaign,
    v_term,
    v_content
  )
  on conflict (event_name, visitor_key_hash, landing_path, touch_hash, event_day)
  do nothing
  returning id into v_inserted_id;

  return jsonb_build_object(
    'accepted', true,
    'event_name', v_event_name,
    'deduplicated', v_inserted_id is null,
    'capture_scope', 'PUBLIC_FUNNEL_V1',
    'raw_visitor_key_stored', false,
    'arbitrary_query_payload_stored', false
  );
end;
$$;

revoke execute on function telemetry_private.capture_public_growth_event_authority(text,text,text,text,text,text,text,text)
from public, service_role;
grant execute on function telemetry_private.capture_public_growth_event_authority(text,text,text,text,text,text,text,text)
to anon, authenticated;

