create or replace function public.start_student_workout_v2(
  p_token text,
  p_command_id text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_context jsonb;
  v_begin jsonb;
  v_link_id uuid;
  v_session_id uuid;
  v_response jsonb;
begin
  v_context := private.student_access_context_v2(p_token, 'start_workout', 12);
  if coalesce((v_context ->> 'ok')::boolean, false) is false then
    return v_context;
  end if;

  v_link_id := (v_context ->> 'link_id')::uuid;
  v_begin := private.student_access_command_begin_v2(v_link_id, 'start_workout', p_command_id);
  if v_begin ->> 'mode' <> 'new' then
    return v_begin -> 'response';
  end if;

  v_session_id := public.start_student_workout(p_token);
  v_response := jsonb_build_object('session_id', v_session_id, 'replayed', false);
  perform private.student_access_command_finish_v2(v_link_id, 'start_workout', p_command_id, v_response);
  return v_response;
end;
$$;

